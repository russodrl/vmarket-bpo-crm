 assert.deepEqual(errors,[]);
 console.log('PASS',mobile?'mobile touch':'desktop','bottom scrollbar scrolls left/right in sync, visible gear, add/remove/persist columns, create/save/apply RJ filter, excludes SP, no JS errors (mock API)');
