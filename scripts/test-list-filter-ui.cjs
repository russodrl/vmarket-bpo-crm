 const bar=page.getByRole('region',{name:'Rolagem horizontal da lista',exact:true});
 await bar.waitFor();
 assert(await bar.evaluate(el=>el.scrollWidth>el.clientWidth),'horizontal overflow is available');
 await bar.focus();
 await page.keyboard.press('ArrowRight');
 await page.waitForFunction(()=>{const bar=document.querySelector('[aria-label="Rolagem horizontal da lista"]');const content=bar.parentElement.firstElementChild;return bar.scrollLeft>0 && Math.abs(content.scrollLeft-bar.scrollLeft)<2});
 await page.keyboard.press('ArrowLeft');
 await page.waitForFunction(()=>{const bar=document.querySelector('[aria-label="Rolagem horizontal da lista"]');return bar.scrollLeft===0 && bar.parentElement.firstElementChild.scrollLeft===0});
 const barBox=await bar.boundingBox();
 const contentBox=await bar.locator('..').locator(':scope > div').first().boundingBox();
 assert(barBox.y >= contentBox.y+contentBox.height,'scrollbar is below the list');
 const box=await gear.boundingBox(); assert(box.x>=0 && box.x+box.width <= page.viewportSize().width,'gear visible without horizontal scroll');
 await click(gear);
 await page.getByText('Campos da visualização',{exact:true}).waitFor();
